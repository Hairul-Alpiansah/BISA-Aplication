function selectQuestions(mode) {
  let pool = questionBank.filter(q => q.subject === state.subject);

  if (!pool.length) {
    pool = questionBank;
  }

  if (mode === "hots") {
    const hots = pool.filter(q => q.level === "hots");
    if (hots.length >= 2) pool = hots;
  }

  if (mode === "adaptive") {
    pool = [...pool].sort((a, b) => (a.level === "hots" ? -1 : 1));
  }

  const shuffled = [...pool].sort(() => Math.random() - .5);
  const desired = mode === "quick" ? 5 : Math.min(7, shuffled.length);
  return shuffled.slice(0, desired);
}

function startQuiz(mode = "quick") {
  const questions = selectQuestions(mode);
  quizSession = {
    mode,
    questions,
    index: 0,
    selected: null,
    score: 0,
    checked: false
  };
  renderQuizQuestion();
  openModal("quizModal");
}

function renderQuizQuestion() {
  const s = quizSession;
  if (!s) return;
  if (s.index >= s.questions.length) {
    renderQuizResult();
    return;
  }

  const q = s.questions[s.index];
  const letters = ["A", "B", "C", "D", "E"];
  $("#quizModalContent").innerHTML = `
    <div class="quiz-top">
      <span class="eyebrow">${state.subject.toUpperCase()} • ${s.mode.toUpperCase()}</span>
      <strong>Soal ${s.index + 1} dari ${s.questions.length}</strong>
      <div class="quiz-progress"><span style="width:${((s.index + 1)/s.questions.length)*100}%"></span></div>
    </div>

    <div class="quiz-question">
      <h2>${q.q}</h2>
      <div class="answer-list">
        ${q.options.map((opt, i) => `
          <button class="answer-option" data-answer="${i}">
            <span class="answer-letter">${letters[i]}</span>
            <span>${opt}</span>
          </button>
        `).join("")}
      </div>
      <div id="quizFeedback"></div>
    </div>

    <div class="lesson-footer">
      <span></span>
      <button class="primary-button" id="quizActionBtn" disabled>Periksa Jawaban</button>
    </div>
  `;

  $$("[data-answer]").forEach(btn => btn.addEventListener("click", () => {
    if (s.checked) return;
    s.selected = Number(btn.dataset.answer);
    $$(".answer-option").forEach(o => o.classList.remove("selected"));
    btn.classList.add("selected");
    $("#quizActionBtn").disabled = false;
  }));

  $("#quizActionBtn").addEventListener("click", () => {
    if (!s.checked) {
      checkQuizAnswer();
    } else {
      s.index++;
      s.selected = null;
      s.checked = false;
      renderQuizQuestion();
    }
  });
}

function checkQuizAnswer() {
  const s = quizSession;
  const q = s.questions[s.index];
  s.checked = true;

  $$(".answer-option").forEach(btn => {
    const i = Number(btn.dataset.answer);
    if (i === q.answer) btn.classList.add("correct");
    if (i === s.selected && i !== q.answer) btn.classList.add("wrong");
  });

  if (s.selected === q.answer) s.score++;
  $("#quizFeedback").innerHTML = `
    <div class="quiz-feedback">
      <strong>${s.selected === q.answer ? "✓ Jawaban benar" : "Belum tepat"}</strong>
      <p>${q.explanation}</p>
    </div>
  `;
  $("#quizActionBtn").textContent = s.index === s.questions.length - 1 ? "Lihat Hasil" : "Soal Berikutnya";
}

function renderQuizResult() {
  const s = quizSession;
  const percent = Math.round((s.score / s.questions.length) * 100);
  const xpGain = Math.max(20, s.score * 12);
  state.xp += xpGain;
  state.scores.push(percent);
  if (state.scores.length > 12) state.scores = state.scores.slice(-12);
  state.studyMinutes[state.studyMinutes.length - 1] += 8;
  saveState();

  $("#quizModalContent").innerHTML = `
    <div class="quiz-result">
      <span class="eyebrow">LATIHAN SELESAI</span>
      <h2>${percent >= 80 ? "Bagus! Konsepmu semakin kuat." : "Teruskan, progresmu sedang tumbuh."}</h2>
      <div class="score-circle"><strong>${percent}</strong></div>
      <div class="score-grid">
        <div><small>Benar</small><strong>${s.score}/${s.questions.length}</strong></div>
        <div><small>XP</small><strong>+${xpGain}</strong></div>
        <div><small>Level</small><strong>${percent >= 80 ? "Kuat" : "Latihan"}</strong></div>
      </div>
      <p>${percent >= 80 ? "Kamu siap mencoba soal yang lebih menantang." : "Pelajari kembali konsep yang salah, lalu coba latihan ulang."}</p>
      <div class="hero-actions" style="justify-content:center">
        <button class="secondary-button" data-close-modal="quizModal">Selesai</button>
        <button class="primary-button" id="retryQuizBtn">Coba Lagi</button>
      </div>
    </div>
  `;

  $("#retryQuizBtn").addEventListener("click", () => startQuiz(s.mode));
  renderDashboard();
  renderProgress();
  renderAchievements();
}

