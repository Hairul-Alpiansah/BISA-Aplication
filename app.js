function freshStateForUser(user = currentUser) {
  const level = user?.level === "SMA" ? "SMA" : "SMP";
  const validGrades = Object.keys(curriculum[level] || {});
  const grade = validGrades.includes(user?.grade) ? user.grade : validGrades[0];
  const subject = Object.keys(curriculum[level]?.[grade] || {})[0] || "IPA";
  return {
    ...defaultState,
    level,
    grade,
    subject,
    name: user?.name || "Siswa BISA",
    completedLessons: [],
    scores: [],
    studyMinutes: [0, 0, 0, 0, 0, 0, 0],
    lastLesson: { level, grade, subject, chapterIndex: 0, lessonIndex: 0 }
  };
}

function loadState() {
  if (!currentUser) return freshStateForUser(null);
  try {
    const key = BISAAuth.stateKey(currentUser.id);
    const saved = JSON.parse(localStorage.getItem(key) || "null");
    const base = freshStateForUser(currentUser);
    return {
      ...base,
      ...(saved || {}),
      completedLessons: Array.isArray(saved?.completedLessons) ? saved.completedLessons : [],
      scores: Array.isArray(saved?.scores) ? saved.scores : [],
      studyMinutes: Array.isArray(saved?.studyMinutes) && saved.studyMinutes.length === 7
        ? saved.studyMinutes : [0, 0, 0, 0, 0, 0, 0]
    };
  } catch {
    return freshStateForUser(currentUser);
  }
}

function saveState() {
  if (!currentUser) return;
  localStorage.setItem(BISAAuth.stateKey(currentUser.id), JSON.stringify(state));
}



