function migrateLegacyProgressIfAvailable() {
  if (!currentUser) return false;
  const newKey = BISAAuth.stateKey(currentUser.id);
  if (localStorage.getItem(newKey)) return false;
  const legacy = localStorage.getItem("bisa_state");
  if (!legacy) return false;
  try {
    const old = JSON.parse(legacy);
    const migrated = { ...freshStateForUser(currentUser), ...old, name: currentUser.name };
    localStorage.setItem(newKey, JSON.stringify(migrated));
    localStorage.removeItem("bisa_state");
    return true;
  } catch {
    return false;
  }
}

