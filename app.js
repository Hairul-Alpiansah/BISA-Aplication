function lessonKey(level, grade, subject, chapterIndex, lessonIndex) {
  return [level, grade, subject, chapterIndex, lessonIndex].join("|");
}

function isLessonCompleted(level, grade, subject, chapterIndex, lessonIndex) {
  return state.completedLessons.includes(lessonKey(level, grade, subject, chapterIndex, lessonIndex));
}

function getCurrentSubjects() {
  return Object.keys(curriculum[state.level][state.grade] || {});
}

function getTotalLessons(level = state.level, grade = state.grade, subject = state.subject) {
  const chapters = curriculum[level]?.[grade]?.[subject] || [];
  return chapters.reduce((acc, ch) => acc + ch[1].length, 0);
}

function getCompletedCount(level = state.level, grade = state.grade, subject = state.subject) {
  const prefix = `${level}|${grade}|${subject}|`;
  return state.completedLessons.filter(k => k.startsWith(prefix)).length;
}

function getSubjectProgress(level = state.level, grade = state.grade, subject = state.subject) {
  const total = getTotalLessons(level, grade, subject);
  if (!total) return 0;
  return Math.round((getCompletedCount(level, grade, subject) / total) * 100);
}

function romanClassLabel(level, grade) {
  return level === "SMP" ? `Kelas ${grade}` : `Kelas ${grade}`;
}

function getAverageScore() {
  if (!state.scores.length) return 0;
  return Math.round(state.scores.reduce((a,b) => a+b, 0) / state.scores.length);
}

function getOverallMastery() {
  const levels = ["SMP", "SMA"];
  let total = 0;
  let completed = 0;
  levels.forEach(level => {
    Object.keys(curriculum[level]).forEach(grade => {
      Object.keys(curriculum[level][grade]).forEach(subject => {
        total += getTotalLessons(level, grade, subject);
      });
    });
  });
  completed = state.completedLessons.length;
  const completionScore = total ? Math.min(100, (completed / Math.max(1, 45)) * 100) : 0;
  const scoreContribution = getAverageScore() * .35;
  return Math.min(100, Math.round(completionScore * .65 + scoreContribution));
}

