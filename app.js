function searchCurriculum(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const results = [];

  Object.keys(curriculum).forEach(level => {
    Object.keys(curriculum[level]).forEach(grade => {
      Object.keys(curriculum[level][grade]).forEach(subject => {
        curriculum[level][grade][subject].forEach((chapter, chapterIndex) => {
          if (`${subject} ${chapter[0]}`.toLowerCase().includes(q)) {
            results.push({ level, grade, subject, chapterIndex, lessonIndex: 0, title: chapter[0], subtitle: `${subject} • ${romanClassLabel(level, grade)}` });
          }
          chapter[1].forEach((lesson, lessonIndex) => {
            if (lesson.toLowerCase().includes(q)) {
              results.push({ level, grade, subject, chapterIndex, lessonIndex, title: lesson, subtitle: `${subject} • ${chapter[0]}` });
            }
          });
        });
      });
    });
  });

  return results.slice(0, 30);
}

function renderSearch(query) {
  const results = searchCurriculum(query);
  $("#searchSummary").textContent = results.length
    ? `${results.length} hasil untuk “${query}”.`
    : `Tidak ada hasil untuk “${query}”. Coba kata kunci lain.`;

  $("#searchResults").innerHTML = results.length
    ? results.map((r, i) => `
      <article class="search-result">
        <div class="result-icon">${subjectIcon(r.subject)}</div>
        <div>
          <h3>${r.title}</h3>
          <p>${r.subtitle} • ${r.level} ${r.grade}</p>
        </div>
        <button class="primary-button" data-search-open="${i}">Buka</button>
      </article>
    `).join("")
    : `<div class="panel"><p>Gunakan kata kunci seperti <b>kalor</b>, <b>sel</b>, <b>trigonometri</b>, <b>atom</b>, atau <b>Newton</b>.</p></div>`;

  $$("[data-search-open]").forEach(btn => btn.addEventListener("click", () => {
    const r = results[Number(btn.dataset.searchOpen)];
    openLesson(r.level, r.grade, r.subject, r.chapterIndex, r.lessonIndex);
  }));
}

function openModal(id) {
  const modal = document.getElementById(id);
  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
}

function closeModal(id) {
  const modal = document.getElementById(id);
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
}

function applyTheme() {
  document.body.classList.toggle("dark", state.theme === "dark");
}

